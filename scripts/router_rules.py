"""
router_rules.py
----------------
Phi-4-miniによるLLM判定の前段で、明示的な「コード関連」キーワードを
正規表現で検知するルールベース事前フィルタ。

4日目ノート(サポートAI作製計画/4日目Phi4ロジック設計.md)の方針:
  - 「コード書いて」等の明示語は問答無用でCODE確定させる(VRAM 16GB制約上、
    誤って重いモデルをロードし直すレイテンシを避けるため、Phi-4-mini判定を
    スキップして即CODEにする)。
  - 複合タスク(例:「バグ修正しつつ開発スケジュールも整理して」)は
    優先度ルール(CODE > DEEP > FAST)で単一ルートに倒す。CODEトリガーが
    含まれていればこの関数がCODEを返すため、優先度ルールはこの事前フィルタが
    router.py側で最優先に呼ばれることで実現される。

4日目ノート「⑤ 会話継続時のモデルスワップ実機検証」で発覚した課題への対応(2026-08-04追記):
  - 旧版は「バグ(を)?(直して|修正)」「実装して」のように**助詞や活用形を決め打ち**していたため、
    「バグ**も**直して」「実装し**といて**」のような自然な口語表現に一致せず、複合タスクの
    優先度ルールが実機の会話で静かに発動しないケースが実機検証で見つかった。
  - 対策として、動詞を**ます形の語幹まで**(例: 「実装し」「デバッグし」「レビューし」)で
    区切ることで、そこに続く活用(て/たい/てほしい/しといて/しておいて/してくれ 等)を
    まとめて拾えるようにした。「バグ」も直後の助詞を`.{0,4}`で許容し、「バグを直して」
    「バグも直して」「バグの修正をお願い」等の揺れを吸収する。
  - 広げすぎるとFAST/DEEPの通常文への誤爆(過剰検出)が心配になるが、「実装」「デバッグ」
    「レビュー」「関数」「バグ」のような単語自体がプログラミング文脈以外ではほぼ出てこない
    ため、語幹だけで区切っても誤爆リスクは低いと判断した。
    (`tests/test_router_rules.py`に旧版では拾えなかった口語表現のテストケースを追加して
    デグレードがないことを確認済み)
"""

from __future__ import annotations

import re

# 正規表現の断片。IGNORECASEでまとめてコンパイルする。
CODE_TRIGGERS: list[str] = [
    # 「書いて/書いてほしい/書いといて/書いておいて」等の活用をまとめて拾うため、
    # 動詞のい-音便語幹「書い」までで区切る。
    r"コード(を)?書い",
    # 「実装して/実装したい/実装してほしい/実装しといて/実装しておいて」等を
    # まとめて拾うため、する動詞のます形語幹「実装し」までで区切る。
    r"実装し",
    r"デバッグし",
    # 助詞の揺れ(を/も/は 等)や間に語が挟まるケースを許容するため、
    # 「バグ」から4文字以内に「直し」または「修正」が出てくれば一致とする。
    r"バグ.{0,4}(直し|修正)",
    r"リファクタリング",
    r"レビューし",
    r"def\s+\w+",
    r"class\s+\w+",
    r"```",
    r"エラーが出る",
    r"TypeError|ValueError|SyntaxError|NullPointerException|IndexError|KeyError",
    # 「関数を書いて/作って」に加え、「関数の実装を作ってほしい」等の助詞の揺れも許容。
    r"関数(を)?(書い|作っ)",
    r"正規表現",
    r"マッチしない",
    r"意図通りに(動作|マッチ)しない",
    # 14日目③: 資料・コード生成(Excel/PowerPoint/Word/JSON)の依頼。
    # 「資料」「エクセル」は日常会話にも出てくる語(「資料を読んでいた」
    # 「エクセルって難しいね」)なので、CODE_TRIGGERSの他の語と違って
    # 名詞単独では一致させず、**必ず「依頼動詞」とセット**でのみ一致させる。
    # (tests/test_router_rules.py::TestDocumentGenerationTriggersに誤爆しない
    # ことの確認テストがある)
    r"(エクセル|Excel|スプレッドシート|表).{0,6}(作っ|作成|まとめ|出力|書き出)",
    r"(パワポ|PowerPoint|スライド|プレゼン).{0,6}(作っ|作成|まとめ|出力)",
    r"(Word|ワード|報告書|議事録|レポート).{0,6}(作っ|作成|まとめ|出力|書い)",
    r"(JSON|CSV|YAML).{0,6}(作っ|作成|出力|書き出|変換)",
    r"資料.{0,4}(作っ|作成|まとめ|出力)",
    r"グラフ.{0,4}(作っ|作成|にし|化し)",
]

_CODE_TRIGGER_RE = re.compile("|".join(CODE_TRIGGERS), re.IGNORECASE)


# 6日目ノート「マツコ問題」の追加調査(2026-08-06)で発覚した課題への対応:
# system_prompt_v3.txtに「想起質問(過去に伝えた情報・過去の会話を思い出させる質問)は
# FASTと判断する」という文章ルールと具体例を追加しても、Phi-4-mini(小型モデル)は
# 例文と完全一致しない限りこれを守れず、確信が持てない場合の保守的デフォルトである
# CLARIFYに倒れ続けることが実測で確認された(「私の猫の名前は何ですか?」→FASTでも
# 「私の亀の名前は何ですか?」→CLARIFY、追加した具体例「昨日やった残りの課題を教えて」
# 自体もCLARIFYになった)。
# プロンプトを文章で改善する方式では小型モデルの汎化能力の限界に当たるため、
# CODE_TRIGGERSと同じ「LLMを介さない正規表現による事前確定」方式で対応する。
RECALL_TRIGGERS: list[str] = [
    # 「〜だっけ?」「〜でしたっけ?」は日本語の口語で「以前知った/話した内容を
    # 思い出させてほしい」という想起質問にほぼ限定して使われる言い回しであり、
    # CODE/DEEPの依頼表現とはほぼ重ならないため誤爆リスクが低い。
    r"だっけ",
    r"でしたっけ",
    # 「私の/僕の/自分の 〜 は 何/いつ/どこ/誰 ですか」型:主語がユーザー自身の
    # 所有物・属性についての想起質問。CODEの依頼動詞(書いて/実装し等)を伴わない
    # 限り、この形はほぼ確実に「以前伝えた情報を答えてほしい」を意味する。
    r"(私|僕|自分)の.{1,20}(何|いつ|どこ|誰)(です|でした)?(か|っけ)",
    # 「昨日/前に/この前/さっき/以前 〜 教えて/どうなった/覚えてる」型:
    # 主語が省略されていても過去の会話・作業内容を参照する想起質問。
    r"(昨日|一昨日|先週|さっき|前に|この前|以前).{0,20}(教えて|どうな(った|ってる)|覚えてる)",
]

_RECALL_TRIGGER_RE = re.compile("|".join(RECALL_TRIGGERS), re.IGNORECASE)


# 15日目②: 音楽再生の依頼。14日目③の「資料」と同じく、日常会話への誤爆を
# 避けるため名詞単独では一致させない。「流して」は特に日常会話へ出やすい
# (「聞き流して」「お湯を流して」)ため、直前に否定的な文脈が無いことを見る。
#
# > [!warning] 「流して」の誤爆リスクは「資料」より高い
# > 14日目③では「資料」「エクセル」が日常会話に出ることを警戒して依頼動詞との
# > セット判定にした。今回の「流して」は**それ自体が動詞**で、「聞き流して」
# > 「お湯を流して」「その話は流して」など**否定的・無関係な用法が非常に多い**。
# > 単純な部分一致では確実に誤爆する。
# > 幸い①の一致度ガード(15日目⓪-5)が最後の砦になるため「誤爆しても曲は流れない」が、
# > 誤爆するたびに「見つかりませんでした」と返ってくるのは体験として悪いため、
# > 否定的な用法(聞き流して/お湯を流して)を除外パターンで明示的に弾く。
MEDIA_TRIGGERS: list[str] = [
    # 「聞き流して」「聞き流していい」等、「聞く」の複合語としての「流して」を除外する。
    r"(?<!聞き)(?<!き)流して",
    r"(かけて|再生して|聴かせて|聞かせて)",
]

# 上記MEDIA_TRIGGERSの「流して」は「お湯を流して」「水道を流して」のような
# 日常会話にも一致してしまうため、直前の名詞で除外する専用パターン。
_MEDIA_FALSE_POSITIVE_RE = re.compile(r"(お湯|水|水道).{0,2}流して")

_MEDIA_TRIGGER_RE = re.compile("|".join(MEDIA_TRIGGERS), re.IGNORECASE)


def is_media_request(text: str) -> bool:
    """発話が「曲を流して/かけて/再生して」のような音楽再生の依頼かどうかを判定する。

    「今日は一日音楽を聴いていたよ」のような単なる音楽の話題への言及は、
    MEDIA_TRIGGERSのどの語(依頼動詞)にも一致しないため誤爆しない。
    """
    if _MEDIA_FALSE_POSITIVE_RE.search(text):
        return False
    return bool(_MEDIA_TRIGGER_RE.search(text))


def match_rule_based(text: str) -> str | None:
    """LLM判定の前段で、正規表現により明確に確定できるrouteを返す。

    優先順位:
      1. CODE_TRIGGERSに一致すれば"CODE"(既存。4日目ノート参照)
      2. is_media_request()に一致すれば"MEDIA"(15日目②。「エクセルを流して」のような
         字面上の衝突を避けるため、CODEの後に判定する。CODE_TRIGGERSの資料生成トリガーは
         「流して」を含まないため実際には衝突しない)
      3. RECALL_TRIGGERSに一致すれば"FAST"(6日目ノート「マツコ問題」参照。
         想起質問がPhi-4-miniによってCLARIFYへ誤判定されるのを防ぐ)
      4. どれにも一致しなければNone(呼び出し側がPhi-4-miniによるLLM判定にフォールバック)

    CODEを先にチェックすることで、「前に書いたコードのバグ直して」のような
    想起+コード依頼の複合表現は従来通りCODE優先(4日目の優先度ルール)を維持する。
    """
    if _CODE_TRIGGER_RE.search(text):
        return "CODE"
    if is_media_request(text):
        return "MEDIA"
    if _RECALL_TRIGGER_RE.search(text):
        return "FAST"
    return None
